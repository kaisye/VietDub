type I18nCtx = { t: T; lang: Lang; setLang: (l: Lang) => void };

const I18nContext = createContext<I18nCtx>({ t: vi, lang: "vi", setLang: () => {} });

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    try {
      const saved = localStorage.getItem(LANG_KEY);
      return saved === "en" ? "en" : "vi";
    } catch {
      return "vi";
    }
  });

  const setLang = useCallback((l: Lang) => {
    try { localStorage.setItem(LANG_KEY, l); } catch { /* ignore */ }
    setLangState(l);
  }, []);

  const t = lang === "en" ? en : vi;
  return <I18nContext.Provider value={{ t, lang, setLang }}>{children}</I18nContext.Provider>;
}

export function useT() {
  return useContext(I18nContext);
}

/** Interpolate {key} placeholders in a translation string. */
export function tt(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_, k) => String(values[k] ?? ""));
}
